/**
 * Regenerates src/abi.ts from the Foundry build artifact.
 * Usage: pnpm --filter @paralock/tempo generate:abi   (runs `forge build` first)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const artifactPath = fileURLToPath(
  new URL("../../../contracts/out/ParalockHTLC.sol/ParalockHTLC.json", import.meta.url),
);
const outPath = fileURLToPath(new URL("../src/abi.ts", import.meta.url));

const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as {
  abi: unknown[];
  bytecode: { object: string };
};

const source = `// Generated by scripts/generate-abi.ts from contracts/out/ParalockHTLC.sol/ParalockHTLC.json. Do not edit.

export const paralockHtlcAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** Creation bytecode, for deploying the HTLC (local devnets, tests). */
export const paralockHtlcBytecode = "${artifact.bytecode.object}" as const;
`;

writeFileSync(outPath, source);
console.log(`wrote ${outPath} (${artifact.abi.length} ABI items)`);
