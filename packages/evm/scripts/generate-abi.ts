/**
 * Regenerates src/abi.ts from the Foundry build artifacts.
 * Usage: pnpm --filter @paralock/evm generate:abi   (runs `forge build` first)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** [Solidity contract name, TypeScript identifier prefix, doc comment for the bytecode]. */
const CONTRACTS = [
  ["ParalockHTLC", "paralockHtlc", "Creation bytecode, for deploying the HTLC (local devnets, tests)."],
  [
    "ParalockAdaptorEscrow",
    "paralockAdaptorEscrow",
    "Creation bytecode, for deploying the adaptor escrow (local devnets, tests).",
  ],
  ["MockUSD", "mockUsd", "Creation bytecode of the 6-decimal local \"USDC\" (local devnets, tests only)."],
] as const;

const outPath = fileURLToPath(new URL("../src/abi.ts", import.meta.url));

let source = `// Generated by scripts/generate-abi.ts from contracts/out. Do not edit.\n`;
for (const [name, prefix, doc] of CONTRACTS) {
  const artifactPath = fileURLToPath(new URL(`../../../contracts/out/${name}.sol/${name}.json`, import.meta.url));
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[]; bytecode: { object: string } };
  source += `
/** ABI of \`${name}\`. */
export const ${prefix}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** ${doc} */
export const ${prefix}Bytecode = "${artifact.bytecode.object}" as const;
`;
  console.log(`${name}: ${artifact.abi.length} ABI items`);
}

writeFileSync(outPath, source);
console.log(`wrote ${outPath}`);
