/**
 * Regenerates the contract artifacts from the Foundry build, in two steps:
 *
 * 1. contracts/out → artifacts/<Contract>.json: language-neutral JSON (ABI, creation and runtime bytecode, solc
 *    settings), shared with non-TypeScript consumers. Skipped with `--from-json`.
 * 2. artifacts/<Contract>.json → src/abi.ts (ABIs and creation bytecode) and src/artifacts.ts (the full artifacts).
 *
 * Everything it writes is committed, so building or using the package never needs Foundry.
 * Usage: pnpm --filter @paralock/evm generate:abi   (runs `forge build` first)
 *        node scripts/generate-abi.ts --from-json    (only step 2)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** [Solidity contract name, TypeScript identifier prefix, artifact constant, doc comment for the bytecode]. */
const CONTRACTS = [
  ["ParalockHTLC", "paralockHtlc", "PARALOCK_HTLC_ARTIFACT", "Creation bytecode, for deploying the HTLC (local devnets, tests)."],
  [
    "ParalockAdaptorEscrow",
    "paralockAdaptorEscrow",
    "PARALOCK_ADAPTOR_ESCROW_ARTIFACT",
    "Creation bytecode, for deploying the adaptor escrow (local devnets, tests).",
  ],
  [
    "MockUSD",
    "mockUsd",
    "MOCK_USD_ARTIFACT",
    "Creation bytecode of the 6-decimal local \"USDC\" (local devnets, tests only).",
  ],
] as const;

/** The parts of a Foundry artifact (`contracts/out/<File>.sol/<Contract>.json`) this script reads. */
interface FoundryArtifact {
  abi: unknown[];
  bytecode: { object: string };
  deployedBytecode: { object: string };
  metadata: {
    compiler: { version: string };
    settings: {
      evmVersion: string;
      optimizer: { enabled: boolean; runs: number };
      compilationTarget: Record<string, string>;
    };
  };
}

/** artifacts/<Contract>.json. */
interface JsonArtifact {
  contractName: string;
  /** Source file, relative to `contracts/`. */
  sourceName: string;
  compiler: { version: string; evmVersion: string; optimizer: { enabled: boolean; runs: number } };
  abi: unknown[];
  bytecode: string;
  deployedBytecode: string;
}

const file = (path: string) => fileURLToPath(new URL(path, import.meta.url));
const jsonPath = (name: string) => file(`../artifacts/${name}.json`);

if (!process.argv.includes("--from-json")) {
  mkdirSync(file("../artifacts/"), { recursive: true });
  for (const [name] of CONTRACTS) {
    const built = JSON.parse(readFileSync(file(`../../../contracts/out/${name}.sol/${name}.json`), "utf8")) as FoundryArtifact;
    const { compiler, settings } = built.metadata;
    const artifact: JsonArtifact = {
      contractName: name,
      sourceName: Object.keys(settings.compilationTarget)[0] ?? `src/${name}.sol`,
      compiler: { version: compiler.version, evmVersion: settings.evmVersion, optimizer: settings.optimizer },
      abi: built.abi,
      bytecode: built.bytecode.object,
      deployedBytecode: built.deployedBytecode.object,
    };
    writeFileSync(jsonPath(name), `${JSON.stringify(artifact, null, 2)}\n`);
    console.log(`${name}: ${artifact.abi.length} ABI items, solc ${compiler.version}, ${settings.evmVersion} → ${jsonPath(name)}`);
  }
}

const header = "// Generated by scripts/generate-abi.ts from artifacts/*.json. Do not edit.\n";
let abiSource = header;
let artifactsSource = `${header}import type { Abi, Hex } from "viem";
import {
${CONTRACTS.flatMap(([, prefix]) => [`  ${prefix}Abi,`, `  ${prefix}Bytecode,`]).join("\n")}
} from "./abi.js";

/**
 * A compiled Paralock contract, as \`forge build\` produces it with \`contracts/foundry.toml\` (the same bytes for
 * \`FOUNDRY_NETWORK=tempo\` and \`ethereum\`). The same data is in \`artifacts/<contractName>.json\` for other languages.
 */
export interface ParalockContractArtifact<TAbi extends Abi = Abi> {
  /** Solidity contract name. */
  readonly contractName: string;
  /** Source file, relative to \`contracts/\`. */
  readonly sourceName: string;
  readonly abi: TAbi;
  /** Creation bytecode. None of the contracts takes constructor arguments, so it is deployed as is. */
  readonly bytecode: Hex;
  /** Runtime bytecode as deployed. Immutables are zero-filled here (only MockUSD has one: \`minter\`). */
  readonly deployedBytecode: Hex;
  /** The solc settings that produced the bytecode (from the artifact's metadata). */
  readonly compiler: {
    readonly version: string;
    readonly evmVersion: string;
    readonly optimizer: { readonly enabled: boolean; readonly runs: number };
  };
}
`;

for (const [name, prefix, constant, doc] of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(jsonPath(name), "utf8")) as JsonArtifact;
  const { compiler } = artifact;
  abiSource += `
/** ABI of \`${name}\`. */
export const ${prefix}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** ${doc} */
export const ${prefix}Bytecode = "${artifact.bytecode}" as const;
`;
  artifactsSource += `
/** \`${name}\`: ABI, creation and runtime bytecode, solc settings. */
export const ${constant}: ParalockContractArtifact<typeof ${prefix}Abi> = {
  contractName: "${name}",
  sourceName: "${artifact.sourceName}",
  abi: ${prefix}Abi,
  bytecode: ${prefix}Bytecode,
  deployedBytecode: "${artifact.deployedBytecode}",
  compiler: {
    version: "${compiler.version}",
    evmVersion: "${compiler.evmVersion}",
    optimizer: { enabled: ${compiler.optimizer.enabled}, runs: ${compiler.optimizer.runs} },
  },
};
`;
}

writeFileSync(file("../src/abi.ts"), abiSource);
writeFileSync(file("../src/artifacts.ts"), artifactsSource);
console.log(`wrote ${file("../src/abi.ts")} and ${file("../src/artifacts.ts")}`);
